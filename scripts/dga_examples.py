#!/usr/bin/env python3
"""Rebuild internal/detect/testdata/dga_examples.tsv.

Downloads the README of https://github.com/baderj/domain_generation_algorithms
and collects the "Example Domains" listed for each malware family.

Usage: python3 scripts/dga_examples.py
"""
import re
import urllib.request

URL = "https://raw.githubusercontent.com/baderj/domain_generation_algorithms/master/README.md"
OUT = "internal/detect/testdata/dga_examples.tsv"

text = urllib.request.urlopen(URL).read().decode("utf-8")

rows = []
for block in text.split("<details>")[1:]:
    m = re.search(r"<summary>(.*?)</summary>", block, re.S)
    if not m:
        continue
    family = re.sub(r"\s*\(.*", "", m.group(1)).strip()
    for d in re.findall(r"^\s*-\s*\\?([A-Za-z0-9\\\-_`\]\[^.]+\.[A-Za-z0-9.\-]+)\s*$", block, re.M):
        d = d.replace("\\", "").lower()
        if re.fullmatch(r"[a-z0-9.\-]+", d) and not d.startswith(("http", "johannesbader")):
            rows.append((family, d))

with open(OUT, "w") as f:
    f.write("# Example domains generated by malware DGAs, one per line as family<TAB>domain.\n")
    f.write("# Source: the \"Example Domains\" sections of https://github.com/baderj/domain_generation_algorithms (README.md)\n")
    for family, d in rows:
        f.write(f"{family}\t{d}\n")

print(f"wrote {len(rows)} domains to {OUT}")
